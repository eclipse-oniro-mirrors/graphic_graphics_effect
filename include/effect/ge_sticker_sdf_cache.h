#ifndef GRAPHICS_EFFECT_GE_STICKER_SDF_CACHE_H
#define GRAPHICS_EFFECT_GE_STICKER_SDF_CACHE_H

#include "image/image.h"

namespace OHOS {
namespace Rosen {

// Shared single-entry cache of the decoded sticker SDF for the sticker effects of this
// PR (emboss/laser). The downsample+JFA+decode pipeline is expensive, so the decoded
// image is stored per sticker identity and spread factor and reused across effects
// instead of being regenerated by each effect independently.
class GEStickerSDFCache {
public:
    GEStickerSDFCache() = delete;
    ~GEStickerSDFCache() = delete;

    static std::shared_ptr<Drawing::Image> MakeCachedDecodedStickerSDFImage(
        Drawing::Canvas& canvas, const std::shared_ptr<Drawing::Image>& sticker, float requiredRangePx);
};

} // namespace Rosen
} // namespace OHOS

#endif // GRAPHICS_EFFECT_GE_STICKER_SDF_CACHE_H
